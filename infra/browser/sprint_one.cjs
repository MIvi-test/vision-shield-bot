// Disposable synthetic accounts only. No cookies, request bodies or traces saved.
const assert = require('node:assert/strict')
const { chromium } = require('playwright')

;(async () => {
  const browser = await chromium.launch({ headless: true })
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  const page = await context.newPage()
  page.setDefaultTimeout(20000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    await page.goto(process.env.PANEL_URL, { waitUntil: 'networkidle' })
    await page.getByRole('heading', { name: 'Вход', exact: true }).waitFor()
    await page.screenshot({ path: '/artifacts/login.png', fullPage: true })
    await page.getByLabel('Логин', { exact: true }).fill('smoke-moderator')
    await page.getByLabel('Пароль', { exact: true }).fill('incorrect-for-test')
    await page.getByRole('button', { name: 'Войти', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Неверный логин или пароль.' }).waitFor()
    await page.getByLabel('Пароль', { exact: true }).fill(process.env.PANEL_PASSWORD)
    await page.getByRole('button', { name: 'Войти', exact: true }).click()
    await page.getByRole('table').waitFor()
    assert.equal(await page.locator('tbody tr').count(), 3)
    await page.screenshot({ path: '/artifacts/submissions.png', fullPage: true })
    await page.locator('tbody tr').first().getByRole('button').click()
    await page.getByRole('heading', { name: 'Карточка заявки', exact: true }).waitFor()
    assert.match(await page.getByRole('region', { name: 'Карточка заявки' }).innerText(), /demo-v1/)
    await page.screenshot({ path: '/artifacts/detail.png', fullPage: true })
    await page.reload({ waitUntil: 'networkidle' })
    await page.getByRole('table').waitFor()
    await page.getByLabel('Статус').selectOption('awaiting_consent')
    await page.getByText('Заявок пока нет.', { exact: true }).waitFor()
    await page.getByLabel('Статус').selectOption('validating')
    await page.getByRole('table').waitFor()
    assert.equal(await page.locator('tbody tr').count(), 3)
    await page.setViewportSize({ width: 375, height: 812 })
    await page.screenshot({ path: '/artifacts/mobile.png', fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), true)
    await page.getByRole('button', { name: 'Выйти', exact: true }).click()
    await page.getByRole('heading', { name: 'Вход', exact: true }).waitFor()
    await page.reload({ waitUntil: 'networkidle' })
    await page.getByRole('heading', { name: 'Вход', exact: true }).waitFor()
    assert.deepEqual(errors, [])
    console.log('PASS: real browser auth, list, detail, filter, reload, mobile and logout')
  } finally {
    await context.close()
    await browser.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
